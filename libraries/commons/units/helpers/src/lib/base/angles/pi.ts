import { Radians } from "@carma/units/types";

export const ZERO_PI = 0 as Radians;
export const PI = Math.PI as Radians;

export const TWO_PI = (Math.PI * 2) as Radians;
export const PI_OVER_TWO = (Math.PI / 2) as Radians;
export const PI_OVER_THREE = (Math.PI / 3) as Radians;
export const PI_OVER_FOUR = (Math.PI / 4) as Radians;
export const PI_OVER_SIX = (Math.PI / 6) as Radians;

export const THREE_PI_OVER_TWO = ((Math.PI * 3) / 2) as Radians;
export const ONE_OVER_TWO_PI = (1 / (Math.PI * 2)) as Radians;

export const MINUS_PI = -PI as Radians;
export const MINUS_TWO_PI = -TWO_PI as Radians;
export const MINUS_PI_OVER_TWO = -PI_OVER_TWO as Radians;
export const MINUS_PI_OVER_THREE = -PI_OVER_THREE as Radians;
export const MINUS_PI_OVER_FOUR = -PI_OVER_FOUR as Radians;
export const MINUS_PI_OVER_SIX = -PI_OVER_SIX as Radians;

export const MINUS_THREE_PI_OVER_TWO = -THREE_PI_OVER_TWO as Radians;
export const MINUS_ONE_OVER_TWO_PI = -ONE_OVER_TWO_PI as Radians;
